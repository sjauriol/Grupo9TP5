    private void llenarListaDNI() {
        DefaultListModel<Integer> modelo = new DefaultListModel<>();
        for (Cliente c : frmMenuPrincipal.directorio.getContactos().values()) {
            if (!modelo.contains(c.getDni())) {
                modelo.addElement(c.getDni());
            }
        }
        lstDni.setModel(modelo);
    }
