    private void btnBorrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBorrarActionPerformed
        int[] filasSeleccionadas = tblClientes.getSelectedRows();

        if (filasSeleccionadas.length == 0) {
            JOptionPane.showMessageDialog(this, "Debe seleccionar al menos un cliente para borrar.");
            return;
        }

        DefaultTableModel model = (DefaultTableModel) tblClientes.getModel();

        // Recorremos de atrás para adelante para no romper los índices
        for (int i = filasSeleccionadas.length - 1; i >= 0; i--) {
            int fila = filasSeleccionadas[i];
            long telefono = (long) model.getValueAt(fila, 5); // columna 5 = Telefono
            frmMenuPrincipal.directorio.borrarContacto(telefono);
            model.removeRow(fila);
        }

        JOptionPane.showMessageDialog(this, "Cliente/s borrado/s correctamente.");
        llenarListaDNI(); // refrescamos la lista de DNIs por si alguno ya no tiene contactos

    }//GEN-LAST:event_btnBorrarActionPerformed


