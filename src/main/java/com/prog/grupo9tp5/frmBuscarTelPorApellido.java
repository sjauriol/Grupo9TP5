    private void lstApellidosValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_lstApellidosValueChanged
        if (evt.getValueIsAdjusting()) {
        return;
    }

    String apellidoSeleccionado = lstApellidos.getSelectedValue();
    if (apellidoSeleccionado == null) {
        return;
    }

    DefaultTableModel model = (DefaultTableModel) tblClientes.getModel();
    model.setRowCount(0);

    for (Map.Entry<Long, Cliente> entry : frmMenuPrincipal.directorio.getContactos().entrySet()) {
        Cliente c = entry.getValue();
        if (c.getApellido().equalsIgnoreCase(apellidoSeleccionado)) {
            model.addRow(new Object[]{
                c.getDni(), c.getApellido(), c.getNombre(),
                c.getDomicilio(), c.getCiudad(), entry.getKey()
            });
        }
    }
    }//GEN-LAST:event_lstApellidosValueChanged


