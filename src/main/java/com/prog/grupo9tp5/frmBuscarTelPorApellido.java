    private void llenarListaApellido() {
    DefaultListModel<String> modelo = new DefaultListModel<>();
    for (Cliente c : frmMenuPrincipal.directorio.getContactos().values()) {
        if (!modelo.contains(c.getApellido())) {
            modelo.addElement(c.getApellido());
        }
    }
    lstApellidos.setModel(modelo);
}

